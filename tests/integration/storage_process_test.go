// These are real independent-process persistence/locking tests. They exercise no
// peer transport and must never be reported as direct/relay messenger evidence.
package integration

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"os"
	"os/exec"
	"path/filepath"
	"testing"
	"time"

	"github.com/zalando/go-keyring"
	"whatsup/internal/desktop"
	"whatsup/internal/storage"
)

type processKeys struct{ value string }

func (k *processKeys) Get() (string, error) {
	if k.value == "" {
		return "", keyring.ErrNotFound
	}
	return k.value, nil
}
func (k *processKeys) Set(value string) error { k.value = value; return nil }

// Inputs and credentials are generated by the parent and sent only over an
// anonymous pipe. The child prints no state, keys, invitations, or endpoints.
type childInput struct {
	Directory   string
	Credential  string
	Fingerprint string
	Busy        bool
}

func TestStorageChildProcess(t *testing.T) {
	if os.Getenv("WHATSUP_STORAGE_TEST_CHILD") != "1" {
		return
	}
	var in childInput
	if err := json.NewDecoder(os.Stdin).Decode(&in); err != nil {
		t.Fatal("invalid synthetic child input")
	}
	keys := &processKeys{value: in.Credential}
	if in.Busy {
		vault, err := storage.Open(in.Directory, keys)
		if vault != nil {
			_ = vault.Close()
		}
		if !errors.Is(err, storage.ErrBusy) {
			t.Fatal("independent process acquired occupied vault")
		}
		return
	}
	service := desktop.New(in.Directory, keys)
	defer service.ServiceShutdown()
	status, err := service.UnlockStorage()
	if err != nil || status.IdentityFingerprint != in.Fingerprint {
		t.Fatal("independent restart did not restore identity")
	}
	if status.MessagingAvailable || !status.PairingAvailable || status.NetworkState != "unavailable" {
		t.Fatal("invitation controls or unavailable messaging boundary changed")
	}
}

func TestIndependentProcessLockAndIdentityRestart(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "private")
	keys := &processKeys{}
	service := desktop.New(dir, keys)
	defer service.ServiceShutdown()
	status, err := service.UnlockStorage()
	if err != nil {
		t.Fatal(err)
	}
	run := func(busy bool) {
		t.Helper()
		input, err := json.Marshal(childInput{Directory: dir, Credential: keys.value, Fingerprint: status.IdentityFingerprint, Busy: busy})
		if err != nil {
			t.Fatal("could not prepare synthetic subprocess")
		}
		defer clear(input)
		ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
		defer cancel()
		command := exec.CommandContext(ctx, os.Args[0], "-test.run=^TestStorageChildProcess$", "-test.count=1")
		command.Env = append(os.Environ(), "WHATSUP_STORAGE_TEST_CHILD=1")
		command.Stdin = bytes.NewReader(input)
		if output, err := command.CombinedOutput(); err != nil {
			// Child output is intentionally never copied into failure logs.
			clear(output)
			t.Fatal("independent process storage assertion failed")
		}
	}
	run(true)
	service.LockStorage()
	run(false)
}
